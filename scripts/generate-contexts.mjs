#!/usr/bin/env node

import { mkdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { loadArtifacts, orderContextRecords, ROOT } from './lib/catalog.mjs';

const check = process.argv.includes('--check');
const records = loadArtifacts();
const byId = new Map(records.map((record) => [record.manifest.id, record]));
const contexts = orderContextRecords(records);
let changed = 0;

function sourceText(rule) {
  const source = byId.get(rule.sourceArtifactId)?.manifest;
  if (!source) throw new Error(`missing context source '${rule.sourceArtifactId}'`);
  if (rule.sourceField === 'summary') return source.summary;
  const refusal = source.refuses?.[rule.sourceIndex];
  if (!refusal) throw new Error(`missing refusal ${rule.sourceIndex} on '${rule.sourceArtifactId}'`);
  return refusal;
}

function generatedBody(manifest) {
  const lines = [
    '<!-- Generated by scripts/generate-contexts.mjs. Edit artifact.json or a provenance source, not this file. -->',
    '',
    `# ${manifest.name}`,
    '',
    `Catalog context: \`${manifest.id}\`. Precedence: ${manifest.context.precedence}. Expires: ${manifest.context.expires || 'never'}.`,
    '',
    '## Rules',
    ''
  ];
  for (const rule of manifest.context.rules) {
    const locator = rule.sourceField === 'refuses'
      ? `${rule.sourceArtifactId}#refuses[${rule.sourceIndex}]`
      : `${rule.sourceArtifactId}#summary`;
    // A refusal describes what its source does not do, so a forbid rule states its own prohibition
    // and keeps the refusal only as provenance.
    // A summary describes what its source does when used, not a duty for every task, so a context
    // states it conditionally rather than as an always-on requirement.
    const source = sourceText(rule);
    const conditional = source && `When the task calls for it: ${source}`;
    const text = rule.sourceField === 'refuses' ? rule.text : conditional;
    if (!text) throw new Error(`${manifest.id} rule '${rule.id}' sourced from refuses needs its own text`);
    lines.push(`- [${rule.id}; effect=${rule.effect}; action=${rule.action}] ${text} (Source: \`${locator}\`)`);
  }
  lines.push('', '## Boundaries', '');
  for (const refusal of manifest.refuses) lines.push(`- ${refusal}`);
  return `${lines.join('\n')}\n`;
}

function renderTarget(record, target) {
  const { manifest } = record;
  const globs = manifest.context.scope === 'glob' ? manifest.context.globs : [];
  const body = generatedBody(manifest);
  if (target === 'claude-code') {
    const frontmatter = globs.length
      ? `---\npaths:\n${globs.map((glob) => `  - ${JSON.stringify(glob)}`).join('\n')}\n---\n\n`
      : '';
    return frontmatter + body;
  }
  if (target === 'cursor') {
    return [
      '---',
      `description: ${JSON.stringify(manifest.summary)}`,
      `globs: ${JSON.stringify(globs.join(','))}`,
      `alwaysApply: ${manifest.context.scope === 'always'}`,
      '---',
      '',
      body
    ].join('\n');
  }
  if (target === 'github-copilot') {
    return `---\napplyTo: ${JSON.stringify(globs.length ? globs.join(',') : '**')}\n---\n\n${body}`;
  }
  throw new Error(`unsupported generated context target '${target}'`);
}

function writeGenerated(file, content) {
  let current = '';
  try { current = readFileSync(file, 'utf8'); } catch {}
  if (current === content) return;
  if (check) {
    process.stderr.write(`${path.relative(ROOT, file)} is stale; run npm run contexts.\n`);
    process.exitCode = 1;
    return;
  }
  mkdirSync(path.dirname(file), { recursive: true });
  const temporary = `${file}.tmp-${process.pid}`;
  writeFileSync(temporary, content);
  renameSync(temporary, file);
  changed += 1;
}

for (const record of contexts) {
  const provenance = new Set(record.manifest.context.provenance);
  const used = new Set(record.manifest.context.rules.map((rule) => rule.sourceArtifactId));
  if (provenance.size !== used.size || [...provenance].some((id) => !used.has(id))) {
    throw new Error(`${record.manifest.id} context.provenance must exactly match the rule sources`);
  }
  for (const target of Object.keys(record.adapters).sort()) {
    const extension = target === 'cursor' ? 'mdc' : 'md';
    const file = path.join(record.directory, 'targets', target, `${record.manifest.slug}.${extension}`);
    writeGenerated(file, renderTarget(record, target));
  }
}

if (!process.exitCode) process.stdout.write(check
  ? `${contexts.length} generated contexts are current.\n`
  : `Generated ${changed} target files for ${contexts.length} contexts.\n`);
