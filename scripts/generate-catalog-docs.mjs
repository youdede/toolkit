// A catalog nobody can read is a catalog nobody adopts. These pages list every artifact so a
// reader can browse the repository without installing anything or running a command.
//
// They are generated from catalog/artifacts.json, never edited, and --check fails the build when
// they drift. A hand-maintained index of 285 artifacts is wrong within a month, and a wrong index
// is worse than none: it sends a reader looking for something that moved.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROOT } from './lib/catalog.mjs';

const OUTPUT = path.join(ROOT, 'docs', 'catalog');

const KINDS = [
  {
    kind: 'skill',
    file: 'skills.md',
    title: 'Skills',
    lead: 'A procedure an agent loads when a task matches. Each states the evidence it needs, the scope it will not widen into, and what it refuses to do.'
  },
  {
    kind: 'hook',
    file: 'hooks.md',
    title: 'Hooks',
    lead: 'A deterministic gate that inspects a command before it runs and blocks it. No model sits in the decision path, so the same input always produces the same verdict.'
  },
  {
    kind: 'subagent',
    file: 'subagents.md',
    title: 'Subagents',
    lead: 'A specialist with a deliberately narrow brief. None may edit, execute, or approve anything, and each must report what it could not verify.'
  }
];

const RISK = { high: 'high', medium: 'medium', low: 'low' };

// A table cell cannot carry a raw pipe or a line break without breaking the row.
const cell = (value) => String(value ?? '').replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ').trim();

function targetList(artifact) {
  const targets = (artifact.targets ?? []).map((t) => (typeof t === 'string' ? t : t.target)).sort();
  return targets.length === 6 ? 'all six' : targets.join(', ');
}

function kindPage({ kind, title, lead }, artifacts) {
  const mine = artifacts.filter((a) => a.kind === kind)
    .sort((a, b) => a.domain.localeCompare(b.domain) || a.category.localeCompare(b.category) || a.slug.localeCompare(b.slug));

  const lines = [
    `# ${title}`,
    '',
    '<!-- Generated by scripts/generate-catalog-docs.mjs. Do not edit; run `npm run catalog:docs`. -->',
    '',
    lead,
    '',
    `${mine.length} of them. Install one with \`npx @youdede/toolkit add <slug> --target <runtime> --scope project\`, or read what it refuses first with \`npx @youdede/toolkit info <slug>\`.`,
    ''
  ];

  let domain = null;
  for (const artifact of mine) {
    if (artifact.domain !== domain) {
      domain = artifact.domain;
      lines.push('', `## ${domain}`, '', '| Slug | What it does | Risk | Runtimes |', '| --- | --- | --- | --- |');
    }
    lines.push(`| \`${cell(artifact.slug)}\` | ${cell(artifact.summary)} | ${RISK[artifact.risk] ?? cell(artifact.risk)} | ${cell(targetList(artifact))} |`);
  }
  lines.push('', '---', '', 'Every row links to an artifact directory under `artifacts/` that carries its full text, its behavioral cases, and its target adapters. The machine-readable index is [catalog/artifacts.json](../../catalog/artifacts.json).', '');
  return lines.join('\n');
}

function packsPage(packs) {
  const sorted = [...packs].sort((a, b) => a.slug.localeCompare(b.slug));
  const lines = [
    '# Packs',
    '',
    '<!-- Generated by scripts/generate-catalog-docs.mjs. Do not edit; run `npm run catalog:docs`. -->',
    '',
    'A pack composes artifacts of different kinds into one outcome, so a single command installs the procedure, the gate, and the specialist that outcome needs.',
    '',
    `${sorted.length} of them. Install one with \`npx @youdede/toolkit add-pack <slug> --target <runtime> --scope project\`.`,
    '',
    '| Slug | What it composes | Artifacts |',
    '| --- | --- | --- |'
  ];
  for (const pack of sorted) {
    const members = pack.artifacts ?? pack.members ?? [];
    lines.push(`| \`${cell(pack.slug)}\` | ${cell(pack.summary ?? pack.description)} | ${members.length} |`);
  }
  lines.push('', '---', '', 'The machine-readable index is [catalog/packs.json](../../catalog/packs.json).', '');
  return lines.join('\n');
}

function indexPage(artifacts, packs) {
  const count = (kind) => artifacts.filter((a) => a.kind === kind).length;
  return [
    '# Catalog',
    '',
    '<!-- Generated by scripts/generate-catalog-docs.mjs. Do not edit; run `npm run catalog:docs`. -->',
    '',
    `Every artifact in the repository, listed so it can be read before it is installed. ${artifacts.length} artifacts and ${packs.length} packs.`,
    '',
    '| Page | Count | What it holds |',
    '| --- | --- | --- |',
    `| [Skills](skills.md) | ${count('skill')} | Procedures an agent loads when a task matches |`,
    `| [Hooks](hooks.md) | ${count('hook')} | Deterministic gates that block a command before it runs |`,
    `| [Subagents](subagents.md) | ${count('subagent')} | Specialists with a narrow brief and no authority to act |`,
    `| [Packs](packs.md) | ${packs.length} | The above composed into one outcome |`,
    '',
    'These pages are generated from the catalog and checked by `npm run check`, so they cannot drift from what the repository actually contains.',
    ''
  ].join('\n');
}

export function buildCatalogDocs(root = ROOT) {
  const artifacts = JSON.parse(readFileSync(path.join(root, 'catalog', 'artifacts.json'), 'utf8'));
  const packsRaw = JSON.parse(readFileSync(path.join(root, 'catalog', 'packs.json'), 'utf8'));
  const list = artifacts.artifacts ?? artifacts;
  const packs = packsRaw.packs ?? packsRaw;
  const pages = new Map();
  for (const definition of KINDS) pages.set(definition.file, kindPage(definition, list));
  pages.set('packs.md', packsPage(packs));
  pages.set('README.md', indexPage(list, packs));
  return pages;
}

function main() {
  const check = process.argv.includes('--check');
  const pages = buildCatalogDocs();
  const stale = [];
  if (!check) mkdirSync(OUTPUT, { recursive: true });
  for (const [name, content] of pages) {
    const file = path.join(OUTPUT, name);
    if (check) {
      let actual = null;
      try {
        actual = readFileSync(file, 'utf8');
      } catch {
        actual = null;
      }
      if (actual !== content) stale.push(path.relative(ROOT, file));
    } else {
      writeFileSync(file, content);
    }
  }
  if (check && stale.length > 0) {
    for (const file of stale) process.stderr.write(`${file} is stale\n`);
    process.stderr.write('run npm run catalog:docs\n');
    process.exit(1);
  }
  process.stdout.write(check
    ? `✓ catalog pages match the catalog across ${pages.size} files\n`
    : `Wrote ${pages.size} catalog pages to docs/catalog.\n`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
