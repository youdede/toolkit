function temporary(context, prefix) {
  const directory = mkdtempSync(path.join(os.tmpdir(), prefix));
  context.after(() => rmSync(directory, { recursive: true, force: true }));
  return directory;
}

function git(cwd, args) {
  const result = spawnSync('git', args, { cwd, encoding: 'utf8', env: cleanGitEnvironment() });
  assert.equal(result.status, 0, result.stderr);
  return result.stdout;
}

function initRepository(directory) {
  git(directory, ['init', '-q']);
  git(directory, ['config', 'user.email', 'tests@youdede.invalid']);
  git(directory, ['config', 'user.name', 'youdede tests']);
}

test('generated file guard uses narrow path and marker evidence', (context) => {
  const directory = temporary(context, 'youdede-generated-');
  mkdirSync(path.join(directory, 'src'));
  writeFileSync(path.join(directory, 'src', 'api.ts'), '// Code generated by schema compiler. DO NOT EDIT.\nexport const x = 1;\n');

  const existingInput = { cwd: directory, tool_input: { file_path: 'src/api.ts', new_string: 'export const x = 2;' } };
  const existing = evaluateGenerated(existingInput, collectGenerated(existingInput));
  assert.equal(existing.exitCode, 2);
  assert.equal(existing.ruleId, 'generated-existing-marker');

  const namedInput = { cwd: directory, tool_input: { file_path: 'src/types.generated.ts', content: 'export type X = string;\n' } };
  assert.equal(evaluateGenerated(namedInput, collectGenerated(namedInput)).ruleId, 'generated-path');

  const proposedInput = { cwd: directory, tool_input: { file_path: 'src/new.ts', content: '// @generated\nexport {}' } };
  assert.equal(evaluateGenerated(proposedInput, collectGenerated(proposedInput)).ruleId, 'generated-proposed-marker');

  const broadDirectory = { cwd: directory, tool_input: { file_path: 'dist/hand-authored.ts', content: 'export {}' } };
  assert.equal(evaluateGenerated(broadDirectory, collectGenerated(broadDirectory)).exitCode, 0);
  const markerInOrdinaryText = { cwd: directory, tool_input: { file_path: 'src/note.ts', content: 'const note = "this may be generated later";' } };
  assert.equal(evaluateGenerated(markerInOrdinaryText, collectGenerated(markerInOrdinaryText)).exitCode, 0);
});

