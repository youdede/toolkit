test('migration safety guard recognizes only explicit destructive command forms', () => {
  const defaultContext = {};
  const blocked = [
    ['dropdb production', 'database-drop-command'],
    ['npx prisma migrate reset --force', 'orm-database-reset'],
    ['bundle exec rails db:drop', 'framework-database-reset'],
    ['php artisan migrate:fresh --seed', 'framework-database-reset'],
    ['npx typeorm schema:drop', 'schema-drop-command']
  ];
  for (const [command, ruleId] of blocked) {
    const result = evaluateMigration({ tool_input: { command } }, defaultContext);
    assert.equal(result.ruleId, ruleId, command);
    assert.doesNotMatch(result.message, new RegExp(command.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')));
  }
  for (const command of ['echo "prisma migrate reset"', 'prisma migrate status', 'rails db:migrate', 'psql -c "SELECT 1"']) {
    assert.equal(evaluateMigration({ tool_input: { command } }, defaultContext).exitCode, 0, command);
  }

  for (const command of [
    'exec time noglob command env FOO=x npx prisma migrate reset',
    "bash -lc 'dropdb production'",
    "'dropdb' production"
  ]) assert.notEqual(evaluateMigration({ tool_input: { command } }, defaultContext).exitCode, 0, command);
  assert.equal(evaluateMigration({ tool_input: { command: "bash -c '$SCRIPT'" } }, defaultContext).ruleId, 'migration-command-uninspectable');
  for (const command of ['env -C / dropdb production', 'PATH=/tmp dropdb production', 'drop{db,nope} production']) {
    assert.equal(evaluateMigration({ tool_input: { command } }, defaultContext).ruleId, 'migration-command-uninspectable', command);
  }
});

test('migration safety guard bounds static SQL checks to migration files', (context) => {
  const directory = temporary(context, 'youdede-migration-');
  mkdirSync(path.join(directory, 'db', 'migrations'), { recursive: true });

  const destructive = { cwd: directory, tool_input: { file_path: 'db/migrations/001_drop.sql', content: 'ALTER TABLE users DROP COLUMN legacy_token;' } };
  assert.equal(evaluateMigration(destructive, collectMigration(destructive)).ruleId, 'sql-drop-column');

  const unqualified = { cwd: directory, tool_input: { file_path: 'db/migrations/002_clean.sql', new_string: 'DELETE FROM sessions;' } };
  assert.equal(evaluateMigration(unqualified, collectMigration(unqualified)).ruleId, 'sql-unqualified-delete');
  const qualified = { cwd: directory, tool_input: { file_path: 'db/migrations/003_clean.sql', content: 'DELETE FROM sessions WHERE expired_at < NOW();' } };
  assert.equal(evaluateMigration(qualified, collectMigration(qualified)).exitCode, 0);

  const documentation = { cwd: directory, tool_input: { file_path: 'docs/example.sql', content: 'DROP TABLE users;' } };
  assert.equal(evaluateMigration(documentation, collectMigration(documentation)).exitCode, 0);
  const inertSql = "-- DROP TABLE users;\nINSERT INTO audit(message) VALUES ('DROP DATABASE prod');";
  assert.doesNotMatch(maskSqlCommentsAndStrings(inertSql), /DROP (?:TABLE|DATABASE)/);
  const inert = { cwd: directory, tool_input: { file_path: 'db/migrations/004_audit.sql', content: inertSql } };
  assert.equal(evaluateMigration(inert, collectMigration(inert)).exitCode, 0);

  const tooLarge = { cwd: directory, tool_input: { file_path: 'db/migrations/005_large.sql', content: ' '.repeat(MAX_SQL_BYTES + 1) } };
  assert.equal(evaluateMigration(tooLarge, collectMigration(tooLarge)).ruleId, 'migration-input-too-large');
});

