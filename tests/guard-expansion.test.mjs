test('dependency change guard blocks direct lockfile edits and narrow unsafe flags', (context) => {
  const directory = temporary(context, 'youdede-dependency-');
  const lockInput = { cwd: directory, tool_input: { file_path: 'package-lock.json', content: '{}' } };
  assert.equal(evaluateDependency(lockInput, collectDependency(lockInput)).ruleId, 'dependency-lockfile-direct-edit');
  const manifestInput = { cwd: directory, tool_input: { file_path: 'package.json', content: '{}' } };
  assert.equal(evaluateDependency(manifestInput, collectDependency(manifestInput)).exitCode, 0);

  const blocked = [
    ['npm install --legacy-peer-deps', 'dependency-resolution-bypass'],
    ['pnpm install --no-lockfile', 'lockfile-generation-bypass'],
    ['pip install --trusted-host mirror.invalid package', 'insecure-package-transport'],
    ['composer update --ignore-platform-reqs', 'dependency-resolution-bypass']
  ];
  for (const [command, ruleId] of blocked) {
    const input = { cwd: directory, tool_input: { command } };
    const result = evaluateDependency(input, collectDependency(input));
    assert.equal(result.ruleId, ruleId, command);
    assert.doesNotMatch(result.message, new RegExp(command.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')));
  }
  for (const command of ['npm install', 'npm install --ignore-scripts', 'echo "npm install --force"', 'pnpm install --frozen-lockfile']) {
    const input = { cwd: directory, tool_input: { command } };
    assert.equal(evaluateDependency(input, collectDependency(input)).exitCode, 0, command);
  }
  for (const command of [
    'exec time noglob command env FOO=x npm install --legacy-peer-deps',
    "bash -lc 'pnpm install --no-lockfile'",
    "'pip' install --trusted-host mirror.invalid package"
  ]) {
    const input = { cwd: directory, tool_input: { command } };
    assert.notEqual(evaluateDependency(input, collectDependency(input)).exitCode, 0, command);
  }
  const dynamic = { cwd: directory, tool_input: { command: "bash -c '$SCRIPT'" } };
  assert.equal(evaluateDependency(dynamic, collectDependency(dynamic)).ruleId, 'dependency-command-uninspectable');
  for (const command of ['env -C ../other git commit -m x', 'env GIT_WORK_TREE=$TREE git commit -m x', 'n{pm,ope} install --legacy-peer-deps']) {
    const input = { cwd: directory, tool_input: { command } };
    assert.equal(evaluateDependency(input, collectDependency(input)).ruleId, 'dependency-command-uninspectable', command);
  }
  for (const command of ['git -C ../other commit -m "x"', 'cd ../other && git commit -m "x"']) {
    const input = { cwd: directory, tool_input: { command } };
    assert.equal(evaluateDependency(input, collectDependency(input)).ruleId, 'dependency-commit-scope-unsupported', command);
  }
});

test('dependency fingerprints ignore unrelated package metadata', () => {
  const before = JSON.stringify({ name: 'demo', scripts: { test: 'node --test' }, dependencies: { a: '1' } });
  const scriptsOnly = JSON.stringify({ name: 'demo', scripts: { test: 'node --test --watch' }, dependencies: { a: '1' } });
  const dependencyChange = JSON.stringify({ name: 'demo', scripts: { test: 'node --test' }, dependencies: { a: '2' } });
  assert.equal(dependencyFingerprint('package.json', before), dependencyFingerprint('package.json', scriptsOnly));
  assert.notEqual(dependencyFingerprint('package.json', before), dependencyFingerprint('package.json', dependencyChange));
  const cargoBefore = '[workspace.dependencies]\nserde = "1"\n[target.\'cfg(unix)\'.dependencies]\nnix = "0.28"\n';
  const cargoAfter = '[workspace.dependencies]\nserde = "2"\n[target.\'cfg(unix)\'.dependencies]\nnix = "0.29"\n';
  assert.notEqual(dependencyFingerprint('Cargo.toml', cargoBefore), dependencyFingerprint('Cargo.toml', cargoAfter));
});

