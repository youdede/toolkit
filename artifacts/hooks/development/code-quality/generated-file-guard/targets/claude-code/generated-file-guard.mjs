#!/usr/bin/env node

import { closeSync, existsSync, lstatSync, openSync, readSync, realpathSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const MAX_STDIN_BYTES = 1024 * 1024;
export const MAX_HEADER_BYTES = 64 * 1024;

const GENERATED_MARKERS = [
  /(?:^|\n)\s*(?:\/\/|#|--|;|\/\*)?\s*@generated\b/i,
  /(?:^|\n)\s*(?:\/\/|#|--|;)?\s*code generated\b[^\n]{0,160}\bdo not edit\b/i,
  /(?:^|\n)\s*(?:\/\/|#|--|;|\/\*)?\s*(?:this file (?:is|was)|automatically|auto-)generated\b[^\n]{0,160}\bdo not edit\b/i,
  /(?:^|\n)\s*(?:\/\/\/?\s*)?<auto-generated(?:\s|\/?>)/i
];

function normalizeRelative(value) {
  return value.split(path.sep).join('/').replace(/^\.\//, '');
}

function readHeader(absolute) {
  const descriptor = openSync(absolute, 'r');
  try {
    const buffer = Buffer.alloc(MAX_HEADER_BYTES);
    const bytes = readSync(descriptor, buffer, 0, buffer.length, 0);
    if (buffer.subarray(0, bytes).includes(0)) return '';
    return buffer.subarray(0, bytes).toString('utf8');
  } finally {
    closeSync(descriptor);
  }
}

function isKnownGeneratedPath(relative) {
  const lower = relative.toLowerCase();
  const segments = lower.split('/');
  if (segments.some((segment) => ['.next', '.nuxt', '.svelte-kit'].includes(segment))) return true;
  const base = path.posix.basename(lower);
  return /(?:\.generated\.[a-z0-9]+|\.gen\.go|\.g\.dart|_pb2(?:_grpc)?\.py|\.designer\.cs)$/.test(base);
}

function hasGeneratedMarker(content) {
  return typeof content === 'string' && GENERATED_MARKERS.some((pattern) => pattern.test(content));
}

function proposedContent(input) {
  const toolInput = input?.tool_input;
  if (!toolInput || typeof toolInput !== 'object') return '';
  if (typeof toolInput.content === 'string') return toolInput.content.slice(0, MAX_HEADER_BYTES);
  if (typeof toolInput.new_string === 'string') return toolInput.new_string.slice(0, MAX_HEADER_BYTES);
  return '';
}

export function collectContext(input, cwd = process.cwd()) {
  const rawPath = input?.tool_input?.file_path || input?.tool_input?.file;
  if (typeof rawPath !== 'string' || !rawPath) return { relevant: false };
  const projectRoot = path.resolve(process.env.CLAUDE_PROJECT_DIR || input?.cwd || cwd);
  const absolute = path.resolve(projectRoot, rawPath);
  const relative = normalizeRelative(path.relative(projectRoot, absolute));
  if (relative === '..' || relative.startsWith('../') || path.isAbsolute(relative)) return { relevant: false };

  let existingHeader = '';
  let existingKind = 'absent';
  try {
    // lstat follows symlinked parent directories, so the nearest existing parent must resolve
    // inside the project before anything behind it is read or written.
    let parent = path.dirname(absolute);
    while (!existsSync(parent) && path.dirname(parent) !== parent) parent = path.dirname(parent);
    const escape = path.relative(realpathSync(projectRoot), realpathSync(parent));
    if (escape === '..' || escape.startsWith(`..${path.sep}`) || path.isAbsolute(escape)) {
      return { relevant: true, relative, inspectionError: 'the path resolves outside the project' };
    }
    const stat = lstatSync(absolute);
    if (stat.isSymbolicLink()) existingKind = 'symlink';
    else if (stat.isFile()) {
      existingKind = 'file';
      existingHeader = readHeader(absolute);
    } else existingKind = 'other';
  } catch (error) {
    if (error?.code !== 'ENOENT') return { relevant: true, relative, inspectionError: error.message };
  }
  return { relevant: true, relative, existingHeader, existingKind };
}

export function evaluate(input, context = {}) {
  if (!context.relevant) return { exitCode: 0, message: '' };
  const known = isKnownGeneratedPath(context.relative);
  if (known) {
    return {
      exitCode: 2,
      ruleId: 'generated-path',
      message: `BLOCKED by generated-file-guard [generated-path]: ${context.relative} is an exact or high-confidence generated output. Edit its source or run its generator.`
    };
  }
  if (context.inspectionError) {
    return {
      exitCode: 2,
      ruleId: 'generated-inspection-failed',
      message: `BLOCKED by generated-file-guard [generated-inspection-failed]: ${context.relative} could not be inspected safely. Review the target outside the guarded operation.`
    };
  }
  if (context.existingKind === 'symlink') {
    return {
      exitCode: 2,
      ruleId: 'generated-symlink-uninspected',
      message: `BLOCKED by generated-file-guard [generated-symlink-uninspected]: ${context.relative} is a symlink whose target is deliberately not inspected. Edit the owning source or review the link outside the guarded operation.`
    };
  }
  if (hasGeneratedMarker(context.existingHeader)) {
    return {
      exitCode: 2,
      ruleId: 'generated-existing-marker',
      message: `BLOCKED by generated-file-guard [generated-existing-marker]: ${context.relative} declares that it is generated. Edit its source or run its generator.`
    };
  }
  if (hasGeneratedMarker(proposedContent(input))) {
    return {
      exitCode: 2,
      ruleId: 'generated-proposed-marker',
      message: `BLOCKED by generated-file-guard [generated-proposed-marker]: the proposed content declares itself generated; use the owning generator instead.`
    };
  }
  return { exitCode: 0, message: '' };
}

async function readInput() {
  const chunks = [];
  let size = 0;
  for await (const chunk of process.stdin) {
    size += chunk.length;
    if (size > MAX_STDIN_BYTES) throw new Error(`hook input exceeds ${MAX_STDIN_BYTES} bytes`);
    chunks.push(chunk);
  }
  const raw = Buffer.concat(chunks).toString('utf8');
  try {
    return raw.trim() ? JSON.parse(raw) : {};
  } catch (error) {
    throw new Error(`hook input is not valid JSON: ${error.message}`);
  }
}

async function main() {
  let result;
  try {
    const input = await readInput();
    result = evaluate(input, collectContext(input));
  } catch (error) {
    result = { exitCode: 2, message: `BLOCKED by generated-file-guard [generated-input-invalid]: ${error.message}.` };
  }
  if (result.message) process.stderr.write(`${result.message}\n`);
  process.exitCode = result.exitCode;
}

if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  await main();
}
